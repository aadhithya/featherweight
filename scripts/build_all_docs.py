"""Put the documentation of the repository in one markdown file, `ALL_DOCS.md`, at the root.

    python scripts/build_all_docs.py      # write ALL_DOCS.md (`make all-docs` runs this)

It gathers, in order: the README and the documentation home; the guides in `docs/`; the specs in `docs/specs/`; the book in
`docs/book/`, chapter by chapter in the order of its table of contents, and the book's style guide; and the README of each
example. The book's code (`docs/book/code/`) and the sample files and skills of the examples are left out.

Each page keeps its text. Its title becomes its section, and its own headings nest under it. A link to another page in the file
becomes a link to that page's section; any other relative link, and any relative image, points at the repository on GitHub.
The file is git-ignored: it is a build output, so edit the sources, not this file.
"""

import posixpath
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "ALL_DOCS.md"
REPO = "https://github.com/aadhithya/featherweight"
RAW = "https://raw.githubusercontent.com/aadhithya/featherweight/main"
BOOK = "docs/book"
TITLE = "featherweight: all documentation in one file"
NOTE = (
    "Everything in the repository's documentation, in one file, in order. It is generated by `make all-docs` "
    "(`scripts/build_all_docs.py`) from the README, `docs/` and the examples' READMEs, so edit those, not this file."
)

FENCE = re.compile(r"^\s*(```|~~~)")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*$")
LINK = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)\)")
IMAGE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)\)")
NAV = re.compile(r"<!-- nav:top -->.*?<!-- /nav:top -->\n*|\n*<!-- nav:bottom -->.*?<!-- /nav:bottom -->\n*", re.S)
PART = re.compile(r"^# (?P<title>.+?)\s*$")
CHAPTER = re.compile(r"^- \[[^\]]+\]\((?P<path>[^)\s]+)\)\s*$")


@dataclass
class Head:
    """A heading. `level` is its level in the file (for a heading of a page: its level in the page's own file)."""

    level: int
    text: str
    orig: str = ""  # its anchor in its own file
    anchor: str = ""  # its anchor in ALL_DOCS.md


@dataclass
class Line:
    text: str
    head: Head | None = None
    code: bool = False  # inside a fenced block: copied as it is


@dataclass
class Page:
    """One page of the repository. Its headings go one level below `base`, which is the level of its title."""

    path: str  # repository-relative; "" for the contents, which is written here
    base: int
    lines: list[Line] = field(default_factory=list)
    top: Head = field(default_factory=lambda: Head(1, ""))  # the title, set when the page is read
    orig_map: dict[str, str] = field(default_factory=dict)  # anchor in its own file -> anchor in ALL_DOCS.md

    @property
    def title(self) -> str:
        return plain(self.top.text)


class Anchors:
    """The anchors GitHub makes from headings: a repeated one gets -1, -2, and so on."""

    def __init__(self) -> None:
        self.taken: set[str] = set()
        self.count: dict[str, int] = {}

    def make(self, text: str) -> str:
        base = slug(text)
        n = self.count.get(base, 0)
        while True:
            candidate = base if n == 0 else f"{base}-{n}"
            n += 1
            if candidate not in self.taken:
                break
        self.count[base] = n
        self.taken.add(candidate)
        return candidate


def plain(text: str) -> str:
    """The text of a heading or a link label, without its markup."""
    return LINK.sub(r"\1", text).replace("`", "").replace("*", "")


def slug(text: str) -> str:
    return re.sub(r"[^\w\- ]", "", plain(text).lower()).strip().replace(" ", "-")


def resolve(page_path: str, target: str) -> str:
    return posixpath.normpath(posixpath.join(posixpath.dirname(page_path), target))


def read_page(rel: str, base: int) -> Page:
    text = NAV.sub("", (ROOT / rel).read_text()).strip("\n") + "\n"
    page = Page(path=rel, base=base)
    own = Anchors()
    code = False
    has_title = False
    for raw in text.splitlines():
        if FENCE.match(raw):
            code = not code
            page.lines.append(Line(raw, code=True))
            continue
        match = None if code else HEADING.match(raw)
        if match:
            head = Head(len(match.group(1)), match.group(2), orig=own.make(match.group(2)))
            page.lines.append(Line(raw, head=head))
            if not has_title and head.level == 1:
                page.top, has_title = head, True
        else:
            page.lines.append(Line(raw, code=code))
    if not has_title:
        raise SystemExit(f"{rel} has no title: a `# heading` is needed")
    return page


def parse_summary() -> list[tuple[str, list[str]]]:
    """The parts of the book, each with its chapters' paths (relative to docs/book), from its table of contents."""
    parts: list[tuple[str, list[str]]] = []
    for line in (ROOT / BOOK / "SUMMARY.md").read_text().splitlines():
        if (match := PART.match(line)) and match["title"] != "Summary":
            parts.append((match["title"], []))
        elif match := CHAPTER.match(line):
            parts[-1][1].append(match["path"])
    return parts


def book_items() -> list[Page | Head]:
    items: list[Page | Head] = [read_page(f"{BOOK}/README.md", 3)]
    for part, chapters in parse_summary():
        items.append(Head(3, part))
        items += [read_page(f"{BOOK}/{chapter}", 4) for chapter in chapters]
    items.append(Head(3, "Appendix"))
    items.append(read_page(f"{BOOK}/STYLE.md", 4))
    return items


def pages_in(folder: str, pattern: str, first: str = "README.md", skip: str = "") -> list[str]:
    """The pages matching `pattern` under `folder`, sorted, with the README first (when there is one)."""
    paths = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / folder).glob(pattern) if p.name != skip)
    return sorted(paths, key=lambda p: (not p.endswith(f"/{first}") and p != first, p))


def section(name: str, items: list[Page | Head]) -> list[Page | Head]:
    """A section of the file. Its title is its first page's title when they match, so the name is not written twice."""
    first = items[0]
    if isinstance(first, Page) and first.title == name:
        first.base = 2
        return items
    return [Head(2, name), *items]


def assign_anchors(items: list[Page | Head]) -> None:
    anchors = Anchors()
    for item in items:
        if isinstance(item, Head):
            item.anchor = anchors.make(item.text)
        elif item.path:
            for line in item.lines:
                if line.head:
                    line.head.anchor = anchors.make(line.head.text)
                    item.orig_map[line.head.orig] = line.head.anchor


def rewrite(page: Page, pages: dict[str, Page], text: str) -> str:
    """Point the links of a page at the other pages of the file, and the rest at GitHub."""

    def image(match: re.Match[str]) -> str:
        alt, src = match.groups()
        if src.startswith(("http://", "https://")):
            return match.group(0)
        return f"![{alt}]({RAW}/{resolve(page.path, src)})"

    def link(match: re.Match[str]) -> str:
        label, target = match.groups()
        if target.startswith(("http://", "https://", "mailto:")):
            return match.group(0)
        path, _, frag = target.partition("#")
        if not path:
            anchor = page.orig_map.get(frag)
            return f"[{label}](#{anchor})" if anchor else match.group(0)
        resolved = resolve(page.path, path)
        if resolved in pages:
            other = pages[resolved]
            anchor = other.orig_map.get(frag, other.top.anchor) if frag else other.top.anchor
            return f"[{label}](#{anchor})"
        suffix = f"#{frag}" if frag else ""
        return f"[{label}]({REPO}/blob/main/{resolved}{suffix})"

    return LINK.sub(link, IMAGE.sub(image, text))


def contents(items: list[Page | Head]) -> list[str]:
    out = [NOTE, ""]
    for item in items:
        if isinstance(item, Head):
            out.append(f"{'  ' * (item.level - 2)}- **{plain(item.text)}**")
        else:
            out.append(f"{'  ' * (item.base - 2)}- [{item.title}](#{item.top.anchor})")
    return out


def page_lines(page: Page, pages: dict[str, Page]) -> list[str]:
    """The lines of a page, with its headings one level down and its links rewritten. A link may wrap over lines, so the prose
    is rewritten in runs, and headings and fenced blocks are kept as they are."""
    out: list[str] = []
    prose: list[str] = []

    def flush() -> None:
        if prose:
            out.append(rewrite(page, pages, "\n".join(prose)))
            prose.clear()

    for line in page.lines:
        if line.head:
            flush()
            level = min(6, line.head.level + page.base - 1)
            out.append(f"{'#' * level} {rewrite(page, pages, line.head.text)}")
        elif line.code:
            flush()
            out.append(line.text)
        else:
            prose.append(line.text)
    flush()
    return out


def render(items: list[Page | Head], pages: dict[str, Page]) -> str:
    out: list[str] = []
    for item in items:
        if isinstance(item, Head):
            out += ["", f"{'#' * item.level} {item.text}", ""]
        elif not item.path:
            out += [line.text for line in item.lines]
        else:
            out += ["", "---", "", *page_lines(item, pages)]
    return "\n".join(out).strip("\n") + "\n"


def build() -> tuple[str, int]:
    guides = pages_in("docs", "*.md", first="", skip="README.md")
    specs = pages_in("docs/specs", "*.md")
    examples = pages_in("examples", "**/README.md", first="examples/README.md")
    sections: list[tuple[str, list[Page | Head]]] = [
        ("Overview", [read_page("README.md", 3), read_page("docs/README.md", 3)]),
        ("Guides", [read_page(path, 3) for path in guides]),
        ("Specs", [read_page(path, 3) for path in specs]),
        ("The book", book_items()),
        ("Examples", [read_page(path, 3) for path in examples]),
    ]
    contents_page = Page(path="", base=2)
    items: list[Page | Head] = [Head(1, TITLE), Head(2, "Contents"), contents_page]
    for name, content in sections:
        items += section(name, content)
    assign_anchors(items)
    contents_page.lines = [Line(text) for text in contents(items[3:])]
    pages = {item.path: item for item in items if isinstance(item, Page) and item.path}
    return render(items, pages), len(pages)


def main(argv: list[str]) -> int:
    text, count = build()
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {count} pages, {text.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
